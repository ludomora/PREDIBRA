          <p class="body-text"><strong>Excesso de ultraprocessados ao redor (casa, trabalho, eventos):</strong> Reforce que pode ser realmente tentador comprar esse tipo de alimento, mas que com algumas estratégias é possível se proteger e ser recompensado com refeições caseiras gostosas. Estimule que a pessoa tenha opções in natura ou minimamente processadas à disposição, comprando para sua casa, levando na sua marmita ou buscando locais que vendam opções mais saudáveis fora de casa. Reforce que é importante seguir sua lista de compras no momento de adquirir alimentos, isso evita compras de ultraprocessados não planejadas.</p>
