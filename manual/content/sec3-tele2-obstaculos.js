          <p class="body-text"><strong>Promoções e combos especiais:</strong> Apesar de tentadoras as promoções e combos especiais de alimentos ultraprocessados, estimule a reflexão sobre quais são os interesses da indústria de alimentos - voltado para o lucro e não para a saúde.</p>
