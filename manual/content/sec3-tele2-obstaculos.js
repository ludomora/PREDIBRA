          <p class="body-text"><strong>Falta de parceria para dividir tarefas domésticas:</strong> Caso a pessoa more com outras pessoas, estimule o diálogo para a divisão de tarefas domésticas e a depender do caso, que a pessoa ensine outras para que isso seja possível. Reforce que os outros não farão as atividades da mesma maneira, mas que é uma estratégia para aliviar a sobrecarga e possibilitar a execução de uma alimentação saudável na rotina diária. Caso não seja possível, reforce as estratégias de planejamento, como cozinhar alguns turnos da semana e congelar.</p>
