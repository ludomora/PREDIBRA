          <p class="body-text"><strong>Eventos climáticos (seca, enchentes, queimadas):</strong> Podem levar à redução da disponibilidade de alimentos frescos e aumentar a oferta por ultraprocessados. Neste caso, foque em orientação de adaptação, substituições possíveis e priorização do minimamente processado disponível, sem culpabilizar. Sugira priorizar alimentos mais duráveis e acessíveis (arroz, feijão, lentilha, ovos, leite, farinha de mandioca, macarrão simples, abóbora, cenoura, batata-doce, frutas da estação, congelados ou enlatados como milho, ervilha, sardinha e atum).</p>
