          <p class="body-text"><strong>Ultraprocessados baratos:</strong> Explique que, embora os alimentos ultraprocessados muitas vezes pareçam mais baratos à primeira vista, essa percepção não se confirma quando analisamos o custo por peso, que geralmente é superior ao de alguns alimentos in natura ou minimamente processados. Apesar disso, pesquisas recentes alertam que os ultraprocessados vêm ficando cada vez mais baratos e, sem políticas públicas, podem se tornar mais acessíveis que a comida saudável nos próximos anos. Ressalte que o consumo frequente de ultraprocessados está associado a prejuízos à saúde a longo prazo, como obesidade, diabetes e outras doenças crônicas, o que pode resultar em maiores gastos com saúde no futuro. Trata-se, portanto, de um “barato” apenas aparente, que pode sair caro tanto para a saúde quanto para o bolso.</p>
